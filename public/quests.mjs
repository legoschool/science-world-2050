// 공용 미션(data/missions)의 요약. 퀘스트 수첩, 미스터리 선생님, 목적지 안내가 함께 쓴다.
export const MISSIONS = {};
let loading = null;
export function loadMissions() {
  loading ??= fetch('/api/missions').then((r) => (r.ok ? r.json() : {missions: []})).then((d) => { for (const x of d.missions || []) MISSIONS[x.id] = x; return MISSIONS; }).catch(() => { loading = null; return MISSIONS; });
  return loading;
}
export const questInfo = (id) => QUESTS[id] || MISSIONS[id];

// 단계별 완료 여부 배열을 돌려준다. progress: {g05, g06} 서버 조회 결과(없으면 null)
export function questSteps(id, state, progress = {}) {
  const q = QUESTS[id];
  if (!q) {
    const mi = MISSIONS[id];
    if (!mi) return [];
    const ms = state.missions?.[id], done = ms && ms.run === state.runId ? ms.done || {} : {};
    return mi.taskIds.map((t) => !!done[t]);
  }
  if (id === 'R3-G04') { const done = state.complete ? q.steps.length : Math.min(state.step || 0, q.steps.length); return q.steps.map((_, i) => i < done); }
  if (id === 'R3-G07') { const c = state.crane || {}, n = c.done ? 10 : typeof c.step === 'number' ? c.step : c.answer === 'decrease' ? 3 : c.asked ? 2 : c.released ? 1 : 0; return q.steps.map((_, i) => i < n); }
  const p = id === 'R3-G05' ? progress.g05 : progress.g06;
  if (!p) return q.steps.map(() => false);
  const missing = new Set((p.missing || []).map((m) => m.title));
  return q.steps.map((_, i) => (i < q.need.length ? q.need[i].every((t) => !missing.has(t)) : !!p.completed));
}

